#!/usr/bin/env node
// Lists every image under public/images into lib/image-manifest.ts, so components know which photos exist
// without requesting missing ones (no 404s in a static export). Runs from `predev` and `prebuild`;
// run it by hand with `npm run images` after adding photos while the dev server is up.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = path.join(root, "public");
const imagesDir = path.join(publicDir, "images");
const out = path.join(root, "lib", "image-manifest.ts");
const EXT = /\.(jpe?g|png|webp|avif|gif|svg)$/i;

function walk(dir) {
  let entries;
  try { entries = readdirSync(dir); } catch { return []; }
  return entries.flatMap((name) => {
    if (name.startsWith(".")) return [];
    const full = path.join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) return walk(full);
    return EXT.test(name) && st.size > 0 ? ["/" + path.relative(publicDir, full).split(path.sep).join("/")] : [];
  });
}

const files = walk(imagesDir).sort();
const body =
  "// Generated by scripts/gen-image-manifest.mjs (predev / prebuild / `npm run images`). Do not edit by hand.\n" +
  "// Every image file under public/images, as the path components pass to asset().\n" +
  "export const IMAGE_MANIFEST: readonly string[] = [\n" +
  files.map((f) => `  ${JSON.stringify(f)},\n`).join("") +
  "];\n";

let current = "";
try { current = readFileSync(out, "utf8"); } catch { /* first run */ }
if (current !== body) writeFileSync(out, body);
console.log(`image manifest: ${files.length} files${current === body ? " (unchanged)" : ""}`);
