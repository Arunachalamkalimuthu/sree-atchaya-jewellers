#!/usr/bin/env node
/**
 * Builds docs/TAMIL-REVIEW.md: every UI string, grouped by area (one dictionary file in lib/i18n/dict), as a table of
 * key, English and Tamil, for a native Tamil speaker to review.
 *
 *   node scripts/tamil-review.mjs
 *
 * Re-run it after changing any dictionary. The dictionaries are TypeScript; their only import is a type import, so
 * Node's built-in type stripping (Node 22.13 or newer) is enough to load them.
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { stripTypeScriptTypes } from "node:module";

// Type stripping is still flagged experimental in Node 22; the warning is noise for this script.
process.removeAllListeners("warning");

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dictDir = join(root, "lib/i18n/dict");
const outFile = join(root, "docs/TAMIL-REVIEW.md");

/** Areas in the order a reviewer meets them on the site; any new dictionary file is appended after these. */
const ORDER = ["common", "home", "shop", "checkout", "account", "scheme", "sell", "custom", "app"];

async function loadDict(file) {
  const src = readFileSync(join(dictDir, file), "utf8");
  const js = stripTypeScriptTypes(src, { mode: "strip" });
  const mod = await import(`data:text/javascript;base64,${Buffer.from(js).toString("base64")}`);
  const name = file.replace(/\.ts$/, "");
  const dict = mod[name] ?? Object.values(mod)[0];
  if (!dict?.en || !dict?.ta) throw new Error(`${file}: expected an export with en and ta`);
  // The JSDoc line above `export const` says what the area covers.
  const doc = src.match(/\/\*\*\s*([\s\S]*?)\s*\*\/\s*export const/);
  const about = doc ? doc[1].split("\n").map((l) => l.replace(/^\s*\*\s?/, "").trim()).join(" ").trim() : "";
  return { name, about, dict };
}

/** Table-cell safe: escape pipes, keep line breaks visible. */
const cell = (s) => (s ?? "").replace(/\\/g, "\\\\").replace(/\|/g, "\\|").replace(/\r?\n/g, "<br>");

/** Bilingual facts kept in lib/site.config.ts rather than a dictionary (the shop's name, the service-area towns). */
async function loadSiteConfig() {
  const src = readFileSync(join(root, "lib/site.config.ts"), "utf8");
  const js = stripTypeScriptTypes(src, { mode: "strip" });
  const { SITE } = await import(`data:text/javascript;base64,${Buffer.from(js).toString("base64")}`);
  const rows = [["name", SITE.name, SITE.nameTa]];
  SITE.serviceArea.forEach((en, i) => rows.push([`serviceArea[${i}]`, en, SITE.serviceAreaTa[i]]));
  return rows;
}

const files = readdirSync(dictDir).filter((f) => f.endsWith(".ts"));
const rank = (f) => { const i = ORDER.indexOf(f.replace(/\.ts$/, "")); return i === -1 ? ORDER.length : i; };
files.sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));

const areas = [];
for (const f of files) areas.push(await loadDict(f));
const total = areas.reduce((n, a) => n + Object.keys(a.dict.en).length, 0);

const out = [];
out.push("# Tamil review: every UI string");
out.push("");
out.push("Generated by `node scripts/tamil-review.mjs` from `lib/i18n/dict/*.ts`. Do not edit this file by hand; change the dictionary and re-run the script.");
out.push("");
out.push(`This is for a native Tamil speaker to check every string on the site and app: ${total} keys in ${areas.length} areas.`);
out.push("");
out.push("- **Key** is the code name. **English** is the source text. **Tamil** is what Tamil users see.");
out.push("- Words in braces, such as `{amount}` or `{g}`, are filled in by the site (an amount, a weight, a name). Keep them as they are, in whatever position reads naturally.");
out.push("- The shop's own terms should stay: சேதாரம், செய்கூலி, முன்பதிவு, தங்க நாணயம், இன்றைய சிறப்பு சலுகை, தங்க சேமிப்பு திட்டம்.");
out.push("- Mark corrections next to the row, or send the key with the new Tamil.");
out.push("");
out.push("## Areas");
out.push("");
for (const a of areas) out.push(`- [${a.name}](#${a.name}) (${Object.keys(a.dict.en).length} keys)`);
out.push("- [site.config](#siteconfig) (shop name and service-area towns)");
out.push("");

for (const a of areas) {
  out.push(`## ${a.name}`);
  out.push("");
  if (a.about) { out.push(a.about); out.push(""); }
  out.push("| Key | English | Tamil |");
  out.push("|---|---|---|");
  for (const key of Object.keys(a.dict.en)) {
    out.push(`| \`${key}\` | ${cell(a.dict.en[key])} | ${cell(a.dict.ta[key] ?? "(missing)")} |`);
  }
  out.push("");
}

out.push("## site.config");
out.push("");
out.push("Names kept in `lib/site.config.ts` with their Tamil form. The address lines, phone numbers, email and the Facebook page name are shown as the shop publishes them and are not translated.");
out.push("");
out.push("| Key | English | Tamil |");
out.push("|---|---|---|");
for (const [key, en, ta] of await loadSiteConfig()) out.push(`| \`${key}\` | ${cell(en)} | ${cell(ta)} |`);
out.push("");

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, out.join("\n"));
console.log(`Wrote docs/TAMIL-REVIEW.md: ${total} keys in ${areas.length} areas.`);
